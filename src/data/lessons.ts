export function getLesson(id: string): Lesson {
  const found = lessons.find((lesson) => lesson.id === id);
  if (!found) {
    throw new Error(`Unknown lesson id: ${id}`);
  }
  return found;
}

export function getReadyLesson(id: string): ReadyLesson {
  const lesson = getLesson(id);
  if (lesson.status !== 'ready') {
    throw new Error(`Lesson is not ready: ${id}`);
  }
  return lesson;
}
